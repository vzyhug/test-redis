-- Atomically reconcile legacy session indexes, enforce the per-user limit,
-- evict oldest sessions, and create the new session.
-- KEYS: user session Set, session order ZSET, login counter, new session Hash,
--       username lock String, username failure-event ZSET.
-- ARGV: userId, sessionId, username, role, device, ip, loginTime,
--       creation timestamp (milliseconds), TTL (seconds), maximum sessions.
-- AUDIT_HELPERS

local sessionsKey = KEYS[1]
local orderKey = KEYS[2]
local countKey = KEYS[3]
local newSessionKey = KEYS[4]
local lockKey = KEYS[5]
local failureEventsKey = KEYS[6]
local auditGlobalKey = KEYS[7]
local auditUserKey = KEYS[8]

local userId = ARGV[1]
local sessionId = ARGV[2]
local username = ARGV[3]
local role = ARGV[4]
local device = ARGV[5]
local ip = ARGV[6]
local loginTime = ARGV[7]
local createdAtMs = tonumber(ARGV[8])
local ttl = tonumber(ARGV[9])
local maxSessions = tonumber(ARGV[10])
local managementId = ARGV[11]
local loginEventId = ARGV[12]
local autoEventId = ARGV[13]
local auditRetention = tonumber(ARGV[14])
local eventDevice = ARGV[15]
local eventIp = ARGV[16]
local maxIndexRepair = 1000

local function keyType(key)
  return redis.call('TYPE', key).ok
end

local function checkType(key, expected)
  local actual = keyType(key)
  if actual ~= 'none' and actual ~= expected then
    return false, actual
  end
  return true, actual
end

if not createdAtMs or not ttl or not maxSessions or maxSessions < 1 or not managementId or managementId == sessionId then
  return redis.error_reply('invalid session creation arguments')
end
if not auditRetention or auditRetention < 1 or not loginEventId or not autoEventId then
  return redis.error_reply('invalid audit arguments')
end

local ok, actual = checkType(sessionsKey, 'set')
if not ok then return redis.error_reply('wrong type for sessions index: ' .. actual) end
ok, actual = checkType(orderKey, 'zset')
if not ok then return redis.error_reply('wrong type for session order index: ' .. actual) end
ok, actual = checkType(countKey, 'string')
if not ok then return redis.error_reply('wrong type for login counter: ' .. actual) end
ok, actual = checkType(newSessionKey, 'hash')
if not ok then return redis.error_reply('wrong type for new session key: ' .. actual) end
ok, actual = checkType(lockKey, 'string')
if not ok then return redis.error_reply('wrong type for login lock: ' .. actual) end
ok, actual = checkType(failureEventsKey, 'zset')
if not ok then return redis.error_reply('wrong type for login failure events: ' .. actual) end
local auditOk, auditError = validateAuditStream(auditGlobalKey)
if not auditOk then return redis.error_reply(auditError) end
auditOk, auditError = validateAuditStream(auditUserKey)
if not auditOk then return redis.error_reply(auditError) end
if redis.call('EXISTS', newSessionKey) == 1 then
  return redis.error_reply('new session id already exists')
end
if redis.call('EXISTS', lockKey) == 1 then
  local lockTtl = redis.call('PTTL', lockKey)
  local retryAfter = lockTtl > 0 and math.ceil(lockTtl / 1000) or tonumber(ARGV[9])
  return { 'LOCKED', tostring(retryAfter) }
end
if redis.call('SCARD', sessionsKey) > maxIndexRepair
  or redis.call('ZCARD', orderKey) > maxIndexRepair then
  return redis.error_reply('session index exceeds safe atomic repair limit')
end

local oldCount = redis.call('GET', countKey)
if oldCount and (not string.match(oldCount, '^%d+$') or not tonumber(oldCount)) then
  return redis.error_reply('login counter is not a non-negative integer')
end

-- Convert the ISO UTC timestamp generated by JavaScript into epoch milliseconds.
-- A malformed legacy timestamp receives score 0 and is ordered lexically by ID.
local function timestampScore(value)
  if not value then return 0 end
  local year, month, day, hour, minute, second, millis = string.match(
    value,
    '^(%d%d%d%d)%-(%d%d)%-(%d%d)T(%d%d):(%d%d):(%d%d)%.(%d%d%d)Z$'
  )
  year, month, day = tonumber(year), tonumber(month), tonumber(day)
  hour, minute, second, millis = tonumber(hour), tonumber(minute), tonumber(second), tonumber(millis)
  if not year or not month or month < 1 or month > 12 or not day or day < 1 or day > 31
    or not hour or hour > 23 or not minute or minute > 59 or not second or second > 59
    or not millis then
    return 0
  end

  local adjustedYear = year
  if month <= 2 then adjustedYear = adjustedYear - 1 end
  local era = math.floor(adjustedYear / 400)
  local yearOfEra = adjustedYear - era * 400
  local adjustedMonth = month + (month > 2 and -3 or 9)
  local dayOfYear = math.floor((153 * adjustedMonth + 2) / 5) + day - 1
  local dayOfEra = yearOfEra * 365 + math.floor(yearOfEra / 4) - math.floor(yearOfEra / 100) + dayOfYear
  local daysSinceEpoch = era * 146097 + dayOfEra - 719468
  return (((daysSinceEpoch * 24 + hour) * 60 + minute) * 60 + second) * 1000 + millis
end

-- Merge IDs from both indexes. This also migrates sessions created before the
-- order ZSET existed and repairs missing membership in either index.
local ids = {}
local seen = {}
for _, id in ipairs(redis.call('SMEMBERS', sessionsKey)) do
  if not seen[id] then ids[#ids + 1] = id; seen[id] = true end
end
for _, id in ipairs(redis.call('ZRANGE', orderKey, 0, -1)) do
  if not seen[id] then ids[#ids + 1] = id; seen[id] = true end
end

-- Validate referenced session key types before the first mutation. Redis Lua
-- is atomic with respect to other commands but does not roll back script errors.
local active = {}
local legacyScores = {}
local autoRevoked = {}
for _, id in ipairs(ids) do
  local key = 'session:' .. id
  local sessionType = keyType(key)
  if sessionType ~= 'none' and sessionType ~= 'hash' then
    return redis.error_reply('wrong type for referenced session key')
  end
  if sessionType == 'hash' then
    local owner = redis.call('HGET', key, 'userId')
    if owner == userId then
      active[#active + 1] = id
      local score = redis.call('ZSCORE', orderKey, id)
      if not score then
        legacyScores[id] = timestampScore(redis.call('HGET', key, 'loginTime'))
      end
    end
  end
end

-- Reconcile both indexes. Missing/expired/cross-user references are removed;
-- valid legacy Hashes are indexed by original loginTime, never by refreshed TTL.
for _, id in ipairs(ids) do
  local key = 'session:' .. id
  local owner = redis.call('HGET', key, 'userId')
  if owner == userId then
    redis.call('SADD', sessionsKey, id)
    local score = redis.call('ZSCORE', orderKey, id)
    if not score then
      redis.call('ZADD', orderKey, legacyScores[id] or 0, id)
    end
  else
    redis.call('SREM', sessionsKey, id)
    redis.call('ZREM', orderKey, id)
  end
end

-- Remove oldest active sessions until there is room. ZRANGE breaks equal-score
-- ties lexicographically by Session ID, making same-millisecond ordering stable.
while #active >= maxSessions do
  local oldest = redis.call('ZRANGE', orderKey, 0, 0)[1]
  if not oldest then
    return redis.error_reply('session indexes could not be reconciled')
  end
  local oldKey = 'session:' .. oldest
  autoRevoked[#autoRevoked + 1] = {
    username = redis.call('HGET', oldKey, 'username') or username,
    device = redis.call('HGET', oldKey, 'device') or '',
    ip = redis.call('HGET', oldKey, 'ip') or ''
  }
  redis.call('DEL', oldKey)
  redis.call('SREM', sessionsKey, oldest)
  redis.call('ZREM', orderKey, oldest)
  table.remove(active, 1)
end

redis.call(
  'HSET', newSessionKey,
  'userId', userId,
  'username', username,
  'role', role,
  'device', device,
  'ip', ip,
  'loginTime', loginTime,
  'managementId', managementId
)
redis.call('EXPIRE', newSessionKey, ttl)
redis.call('SADD', sessionsKey, sessionId)
redis.call('ZADD', orderKey, createdAtMs, sessionId)
redis.call('INCR', countKey)
redis.call('DEL', failureEventsKey)

local eventTime = auditNowMs()
local auditWritten = true
for index, revoked in ipairs(autoRevoked) do
  local fields = auditFields(
    autoEventId .. '-' .. tostring(index), 'SESSION_AUTO_REVOKED', '', 'SYSTEM', 'SYSTEM',
    userId, revoked.username, eventTime, 'SUCCESS', revoked.ip, revoked.device, nil, 'MAX_SESSIONS'
  )
  if not appendAudit(auditGlobalKey, auditUserKey, '', fields, auditRetention, eventTime) then auditWritten = false end
end
local loginFields = auditFields(
  loginEventId, 'LOGIN_SUCCESS', userId, role, username, userId, username,
  eventTime, 'SUCCESS', eventIp, eventDevice, nil, ''
)
if not appendAudit(auditGlobalKey, auditUserKey, '', loginFields, auditRetention, eventTime) then auditWritten = false end

return { 'CREATED', sessionId, auditWritten and '1' or '0' }
